package tools

// linkifyfuzzy.go — port of linkify-it's fuzzy bare-domain matching as used
// by markdown-it's core linkify rule (new LinkifyIt() defaults: fuzzyLink
// true, fuzzyIP false) in @a-bonus/google-docs-mcp@1.11.3. Scheme/www/email
// autolinks are already handled by goldmark inline; this scanner runs on the
// remaining plain-text segments and reproduces linkify-it's
// link_no_ip_fuzzy regex semantics: prefix boundary, (domain.)+TLD host,
// optional port, host terminator, and src_path. Regex lookaheads are
// reimplemented as explicit position checks. Offsets are byte offsets into
// the input string (the input here is Go text, unlike JS UTF-16 indices —
// the surrounding code slices with these offsets).

import (
	"strings"
	"unicode"
	"unicode/utf8"
)

type fuzzyLinkMatch struct {
	start int
	end   int
}

// --- character classes (uc.micro categories used by linkify-it's re.mjs) ---

func isZPCc(r rune) bool {
	return unicode.Is(unicode.Z, r) || unicode.Is(unicode.P, r) || unicode.Is(unicode.Cc, r)
}

func isZCc(r rune) bool {
	return unicode.Is(unicode.Z, r) || unicode.Is(unicode.Cc, r)
}

// pseudo_letter = Any minus {>, <, ｜} minus ZPCc.
func isPseudoLetter(r rune) bool {
	if r == '>' || r == '<' || r == '｜' {
		return false
	}
	return !isZPCc(r)
}

// --- TLD set: linkify-it defaults + 2-char ccTLD trie + xn-- ---

var fuzzyTLDDefault = map[string]bool{
	"biz": true, "com": true, "edu": true, "gov": true, "net": true,
	"org": true, "pro": true, "web": true, "xxx": true, "aero": true,
	"asia": true, "coop": true, "info": true, "museum": true, "name": true,
	"shop": true, "рф": true,
}

// tlds2chSrc is linkify-it's autogenerated 2-character TLD alternation,
// copied verbatim from index.mjs.
const tlds2chSrc = `a[cdefgilmnoqrstuwxz]|b[abdefghijmnorstvwyz]|c[acdfghiklmnoruvwxyz]|d[ejkmoz]|e[cegrstu]|f[ijkmor]|g[abdefghilmnpqrstuwy]|h[kmnrtu]|i[delmnoqrst]|j[emop]|k[eghimnprwyz]|l[abcikrstuvy]|m[acdeghklmnopqrstuvwxyz]|n[acefgilopruz]|om|p[aefghklmnrstwy]|qa|r[eosuw]|s[abcdeghijklmnortuvxyz]|t[cdfghjklmnortvwz]|u[agksyz]|v[aceginu]|w[fs]|y[et]|z[amw]`

var fuzzyTLD2ch = expand2chTLDs(tlds2chSrc)

// expand2chTLDs expands the restricted alternation syntax (literal char
// pairs and char+[set] terms) into a set of two-letter strings.
func expand2chTLDs(src string) map[string]bool {
	out := map[string]bool{}
	for _, term := range strings.Split(src, "|") {
		if len(term) == 2 {
			out[term] = true
			continue
		}
		// form: c[chars]
		first := term[0]
		inner := term[2 : len(term)-1]
		for i := 0; i < len(inner); i++ {
			out[string([]byte{first, inner[i]})] = true
		}
	}
	return out
}

// xnExtendedEnd applies the xn--[a-z0-9-]{1,59} TLD alternative greedily
// from pos, returning the end offset (pos when it doesn't match).
func xnExtendedEnd(s string, pos int) int {
	if len(s)-pos < 5 || !strings.EqualFold(s[pos:pos+4], "xn--") {
		return pos
	}
	p := pos + 4
	n := 0
	for p < len(s) && n < 59 {
		c := s[p]
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-') {
			break
		}
		p++
		n++
	}
	if n == 0 {
		return pos
	}
	return p
}

func isFuzzyTLD(label string) bool {
	lower := strings.ToLower(label)
	if fuzzyTLDDefault[lower] {
		return true
	}
	if len(label) == 2 && fuzzyTLD2ch[lower] {
		return true
	}
	// xn--[a-z0-9-]{1,59} (case-insensitive flag on the original regex)
	if len(label) >= 5 && len(label) <= 63 && strings.EqualFold(label[:4], "xn--") {
		rest := label[4:]
		for i := 0; i < len(rest); i++ {
			c := rest[i]
			if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-') {
				return false
			}
		}
		return len(rest) >= 1
	}
	return false
}

// --- host scanning ---

// scanDomainLabel scans one domain label at pos:
// pseudo_letter | pseudo_letter(-|pseudo_letter){0,61}pseudo_letter with the
// regex's greedy-then-backtrack resolution: take the maximal run of
// (pseudo_letter|-) up to 63 runes, then shrink to the largest length whose
// last char is a pseudo_letter. Returns the end offset and ok.
func scanDomainLabel(s string, pos int) (int, bool) {
	if pos >= len(s) {
		return pos, false
	}
	r, size := utf8.DecodeRuneInString(s[pos:])
	if !isPseudoLetter(r) {
		return pos, false
	}
	end := pos + size
	count := 1
	lastGood := end // end of the longest prefix ending in a pseudo_letter
	for count < 63 && end < len(s) {
		r, size = utf8.DecodeRuneInString(s[end:])
		if r == '-' {
			end += size
			count++
			continue
		}
		if !isPseudoLetter(r) {
			break
		}
		end += size
		count++
		lastGood = end
	}
	// run may exceed 63 runes; cap: label length is at most 63
	if count > 63 {
		// walk to the 63-rune boundary
		p, n := pos, 0
		lastGood = pos
		for p < len(s) && n < 63 {
			r, size := utf8.DecodeRuneInString(s[p:])
			p += size
			n++
			if isPseudoLetter(r) {
				lastGood = p
			}
		}
	}
	if lastGood == pos {
		return pos, false
	}
	return lastGood, true
}

// matchFuzzyHosts returns the candidate host ends for (domain\.)+TLD at
// pos, most-consumed first — the JS regex greedily takes every "domain."
// then backtracks one label at a time until the TLD alternation and the
// following port/terminator accept. Callers try candidates in order.
func matchFuzzyHosts(s string, pos int) []int {
	type span struct{ start, end int }
	var labels []span
	p := pos
	for {
		end, ok := scanDomainLabel(s, p)
		if !ok {
			break
		}
		labels = append(labels, span{p, end})
		if end < len(s) && s[end] == '.' {
			p = end + 1
			continue
		}
		break
	}
	var ends []int
	// final label must be a TLD, with at least one preceding "domain."
	for k := len(labels) - 1; k >= 1; k-- {
		label := s[labels[k].start:labels[k].end]
		if k == len(labels)-1 {
			// The xn-- TLD alternative (xn--[a-z0-9-]{1,59}) is greedy over
			// trailing hyphens too, which domain-label syntax forbids — so
			// it can consume past the label end. Try that first (the regex
			// is greedy) when the label opens with xn--.
			if extEnd := xnExtendedEnd(s, labels[k].start); extEnd > labels[k].end {
				ends = append(ends, extEnd)
			}
		}
		if isFuzzyTLD(label) {
			ends = append(ends, labels[k].end)
		}
	}
	return ends
}

// --- port ---

// matchFuzzyPort matches src_port at pos (which is at ':'): the ordered
// alternation 6[0-4]\d{3} | 65[0-4]\d{2} | 655[0-2]\d | 6553[0-5] |
// [1-5]?\d{1,4}. Returns (portEnd, matched).
func matchFuzzyPort(s string, pos int) (int, bool) {
	if pos >= len(s) || s[pos] != ':' {
		return pos, false
	}
	d := func(i int) byte {
		if i < len(s) {
			return s[i]
		}
		return 0
	}
	isDig := func(c byte) bool { return c >= '0' && c <= '9' }
	// fixed 5-digit alternatives
	if isDig(d(pos+5)) && isDig(d(pos+3)) && isDig(d(pos+4)) {
		switch {
		case d(pos+1) == '6' && d(pos+2) >= '0' && d(pos+2) <= '4':
			return pos + 6, true
		case d(pos+1) == '6' && d(pos+2) == '5' && d(pos+3) >= '0' && d(pos+3) <= '4':
			return pos + 6, true
		case d(pos+1) == '6' && d(pos+2) == '5' && d(pos+3) == '5' && d(pos+4) >= '0' && d(pos+4) <= '2':
			return pos + 6, true
		case d(pos+1) == '6' && d(pos+2) == '5' && d(pos+3) == '5' && d(pos+4) == '3' && d(pos+5) >= '0' && d(pos+5) <= '5':
			return pos + 6, true
		}
	}
	// [1-5]?\d{1,4}, greedy: optional lead digit 1-5 then 1-4 digits
	p := pos + 1
	if d(p) >= '1' && d(p) <= '5' && isDig(d(p+1)) {
		p++
	}
	if !isDig(d(p)) {
		return pos, false
	}
	n := 0
	for n < 4 && isDig(d(p)) {
		p++
		n++
	}
	return p, true
}

// --- host terminator ---

// fuzzyTerminatorOK checks src_host_terminator at pos:
// (?=$|>|<|｜|ZPCc) followed by (?!-|_|:\d|.-|.(?!$|ZPCc)).
func fuzzyTerminatorOK(s string, pos int) bool {
	if pos >= len(s) {
		return true
	}
	r, size := utf8.DecodeRuneInString(s[pos:])
	if !(r == '>' || r == '<' || r == '｜' || isZPCc(r)) {
		return false
	}
	next := func(i int) (rune, bool) {
		if i >= len(s) {
			return 0, false
		}
		r2, _ := utf8.DecodeRuneInString(s[i:])
		return r2, true
	}
	switch r {
	case '-', '_':
		return false
	case ':':
		if r2, ok := next(pos + size); ok && r2 >= '0' && r2 <= '9' {
			return false
		}
	case '.':
		r2, ok := next(pos + size)
		if !ok {
			return true // "." at end is allowed
		}
		if r2 == '-' {
			return false
		}
		if !isZPCc(r2) {
			return false // ".x" continues the domain
		}
	}
	return true
}

// --- path (src_path) ---

// pathAlt1Excluded is the first-alternative exclusion set:
// ZCc | > < ｜ | ( ) [ \ ] { } . , " ' ? ! - ;
func pathAlt1Excluded(r rune) bool {
	if isZCc(r) || r == '>' || r == '<' || r == '｜' {
		return true
	}
	switch r {
	case '(', ')', '[', '\\', ']', '{', '}', '.', ',', '"', '\'', '?', '!', '-', ';':
		return true
	}
	return false
}

// matchQuoted consumes open (not ZCc|close)* close with first-close
// semantics (the content class excludes the closing char, so the first
// occurrence terminates). Returns end offset and ok.
func matchQuotedPath(s string, pos int, open, close rune) (int, bool) {
	_, osize := utf8.DecodeRuneInString(s[pos:])
	p := pos + osize
	if p >= len(s) {
		return pos, false
	}
	r, size := utf8.DecodeRuneInString(s[p:])
	if r == close || isZCc(r) {
		return pos, false
	}
	p += size
	for p < len(s) {
		r, size = utf8.DecodeRuneInString(s[p:])
		if r == close {
			return p + size, true
		}
		if isZCc(r) {
			return pos, false
		}
		p += size
	}
	return pos, false
}

// matchBracket consumes open (not ZCc|close)* close where content may be
// empty. Returns end and ok.
func matchBracketPath(s string, pos int, open, close rune) (int, bool) {
	_, osize := utf8.DecodeRuneInString(s[pos:])
	p := pos + osize
	for p < len(s) {
		r, size := utf8.DecodeRuneInString(s[p:])
		if r == close {
			return p + size, true
		}
		if isZCc(r) {
			return pos, false
		}
		p += size
	}
	return pos, false
}

// matchFuzzyPath consumes src_path at pos. Returns the end offset (which may
// equal pos when there is no path).
func matchFuzzyPath(s string, pos int) int {
	if pos >= len(s) {
		return pos
	}
	c := s[pos]
	if c != '/' && c != '?' && c != '#' {
		return pos
	}
	start := pos
	p := pos + 1
	for p < len(s) {
		r, size := utf8.DecodeRuneInString(s[p:])
		switch {
		case !pathAlt1Excluded(r):
			p += size
		case r == '[':
			if end, ok := matchBracketPath(s, p, '[', ']'); ok {
				p = end
			} else {
				goto done
			}
		case r == '(':
			if end, ok := matchBracketPath(s, p, '(', ')'); ok {
				p = end
			} else {
				goto done
			}
		case r == '{':
			if end, ok := matchBracketPath(s, p, '{', '}'); ok {
				p = end
			} else {
				goto done
			}
		case r == '"':
			if end, ok := matchQuotedPath(s, p, '"', '"'); ok {
				p = end
			} else {
				goto done
			}
		case r == '\'':
			if end, ok := matchQuotedPath(s, p, '\'', '\''); ok {
				p = end
				continue
			}
			// '(?=pseudo_letter|-): consume the quote alone
			if p+size < len(s) {
				r2, _ := utf8.DecodeRuneInString(s[p+size:])
				if isPseudoLetter(r2) || r2 == '-' {
					p += size
					continue
				}
			}
			goto done
		case r == '.':
			// try \.{2,}[a-zA-Z0-9%/&] first
			dots := 0
			for p+dots < len(s) && s[p+dots] == '.' {
				dots++
			}
			if dots >= 2 && p+dots < len(s) {
				c2 := s[p+dots]
				if c2 >= 'a' && c2 <= 'z' || c2 >= 'A' && c2 <= 'Z' || c2 >= '0' && c2 <= '9' || c2 == '%' || c2 == '&' || c2 == '/' {
					p += dots + 1
					continue
				}
			}
			// \.(?!ZCc|[.]|$)
			if p+1 < len(s) && s[p+1] != '.' {
				r2, _ := utf8.DecodeRuneInString(s[p+1:])
				if !isZCc(r2) {
					p++
					continue
				}
			}
			goto done
		case r == '-':
			for p < len(s) && s[p] == '-' {
				p++
			}
		case r == ',' || r == ';':
			if p+1 < len(s) {
				r2, _ := utf8.DecodeRuneInString(s[p+1:])
				if !isZCc(r2) {
					p++
					continue
				}
			}
			goto done
		case r == '!':
			q := p
			for q < len(s) && s[q] == '!' {
				q++
			}
			if q < len(s) {
				r2, _ := utf8.DecodeRuneInString(s[q:])
				if !isZCc(r2) && r2 != '!' {
					p = q
					continue
				}
			}
			goto done
		case r == '?':
			if p+1 < len(s) && s[p+1] != '?' {
				r2, _ := utf8.DecodeRuneInString(s[p+1:])
				if !isZCc(r2) {
					p++
					continue
				}
			}
			goto done
		default:
			goto done
		}
	}
done:
	if p == start+1 {
		// [/?#] consumed but no path chars: the regex's first alternative
		// fails; only a bare '/' survives as the path.
		if c == '/' {
			return p
		}
		return start
	}
	return p
}

// --- full match at a position ---

// matchFuzzyAt attempts the link_no_ip_fuzzy group-2 match at pos (host,
// optional port, terminator, path). Returns end offset and ok.
func matchFuzzyAt(s string, pos int) (int, bool) {
	// group-2 leading negative lookahead: first char not in $ + < = > ^ ` | ｜
	r, _ := utf8.DecodeRuneInString(s[pos:])
	switch r {
	case '$', '+', '<', '=', '>', '^', '`', '|', '｜':
		return pos, false
	}
	for _, hostEnd := range matchFuzzyHosts(s, pos) {
		p := hostEnd
		if portEnd, matched := matchFuzzyPort(s, p); matched {
			if fuzzyTerminatorOK(s, portEnd) {
				return matchFuzzyPath(s, portEnd), true
			}
			// Dropping the port can never help: a matched port means the
			// terminator would sit at ':' followed by a digit, which the
			// terminator's (?!:\d) rejects.
			continue
		}
		if fuzzyTerminatorOK(s, p) {
			return matchFuzzyPath(s, p), true
		}
	}
	return pos, false
}

// fuzzyPrefixOK checks group 1: ^, or a preceding char in
// {$+<=>^`|｜} ∪ ZPCc — where the (?![.:/\-_@]) lookahead excludes those
// six chars from acting as the prefix char (it sits before the prefix
// char in the regex, not before the match start). Note the upstream
// template literal's "\\-" collapses to an escaped dash in the compiled
// regex, so the class is .:/-_@ and does NOT contain a backslash.
func fuzzyPrefixOK(s string, pos int) bool {
	if pos == 0 {
		return true
	}
	prev, _ := utf8.DecodeLastRuneInString(s[:pos])
	switch prev {
	case '.', ':', '/', '-', '_', '@':
		return false
	}
	if prev == '$' || prev == '+' || prev == '<' || prev == '=' || prev == '>' ||
		prev == '^' || prev == '`' || prev == '|' || prev == '｜' {
		return true
	}
	return isZPCc(prev)
}

// scanFuzzyLinks reproduces linkify-it's match() restricted to fuzzy links
// (schema ""), leftmost-first, non-overlapping.
func scanFuzzyLinks(s string) []fuzzyLinkMatch {
	var out []fuzzyLinkMatch
	for pos := 0; pos < len(s); {
		if fuzzyPrefixOK(s, pos) {
			if end, ok := matchFuzzyAt(s, pos); ok {
				out = append(out, fuzzyLinkMatch{start: pos, end: end})
				pos = end
				continue
			}
		}
		_, size := utf8.DecodeRuneInString(s[pos:])
		pos += size
	}
	return out
}
